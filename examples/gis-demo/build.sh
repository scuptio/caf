#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"

# 1. Compile the computation to a WASM module (core wasm + caf host ABI).
cargo build --release --target wasm32-unknown-unknown --manifest-path "$ROOT/Cargo.toml"
cp "$ROOT/target/wasm32-unknown-unknown/release/gis_demo.wasm" "$ROOT/gis-demo.wasm"

# 2. Generate the second data format (WKB) from the source GeoJSON.
python3 "$ROOT/make_data.py"

# 3. Pack data + interface + wasm into a single .caf artifact.
caf-tool build -c "$ROOT/build.toml" -o "$ROOT/demo.caf"

# 4. Sealed variant (encryption demo; spec §8). The convergent key_seed makes
#    the build byte-reproducible and lets caf-tool print the content key; the
#    web demo reads it from web/sealed-key.js. Demo key material is public on
#    purpose — it demonstrates the mechanism, not secrecy.
out="$(caf-tool build -c "$ROOT/build-sealed.toml" -o "$ROOT/demo-sealed.caf")"
echo "$out"
key="$(echo "$out" | grep '^content key: ' | cut -d' ' -f3)"
printf '// Generated by build.sh (convergent sealed demo build). Public demo key.\nexport const DEMO_CONTENT_KEY = "%s";\n' "$key" > "$ROOT/web/sealed-key.js"
caf-tool verify "$ROOT/demo-sealed.caf"
caf-tool verify "$ROOT/demo-sealed.caf" --key "$key"

echo "built $ROOT/demo.caf and $ROOT/demo-sealed.caf"
